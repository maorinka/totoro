// Build-time generator: embed files into a C++ source as byte arrays.
//
//   embed <out.cpp> <root-dir> <relative-path>...
//
// Produces wisp::find_asset() over the given files, with a MIME type derived
// from each extension. Paths are stored relative to <root-dir>.
#include <cstdio>
#include <fstream>
#include <iostream>
#include <iterator>
#include <string>
#include <vector>

static std::string mime_for(const std::string &p) {
	auto ends = [&](const char *s) {
		std::string e(s);
		return p.size() >= e.size() && p.compare(p.size() - e.size(), e.size(), e) == 0;
	};
	if (ends(".html")) return "text/html; charset=utf-8";
	if (ends(".css")) return "text/css; charset=utf-8";
	if (ends(".js")) return "text/javascript; charset=utf-8";
	if (ends(".svg")) return "image/svg+xml";
	if (ends(".json")) return "application/json";
	if (ends(".png")) return "image/png";
	return "application/octet-stream";
}

int main(int argc, char **argv) {
	if (argc < 3) {
		std::cerr << "usage: embed <out.cpp> <root-dir> <file>...\n";
		return 2;
	}
	std::ofstream out(argv[1]);
	out << "// Generated by tools/embed.cpp -- do not edit.\n#include \"assets.hpp\"\n#include <cstring>\n\n"
	       "namespace wisp {\nnamespace {\n";
	std::vector<std::string> names;
	for (int i = 3; i < argc; i++) {
		std::string rel = argv[i];
		std::ifstream f(std::string(argv[2]) + "/" + rel, std::ios::binary);
		if (!f) {
			std::cerr << "embed: cannot read " << argv[2] << "/" << rel << "\n";
			return 1;
		}
		std::string data((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
		// unsigned char with values 0..255: valid whether plain char is signed
		// (x86-64) or unsigned (aarch64, ppc64le, s390x), where a negative
		// initialiser in a char array is a narrowing error.
		out << "const unsigned char a" << (i - 3) << "[] = {";
		for (size_t k = 0; k < data.size(); k++) {
			if (k % 24 == 0)
				out << "\n";
			out << (unsigned)(unsigned char)data[k] << ",";
		}
		out << "0};\n";
		names.push_back(rel);
	}
	out << "const Asset table[] = {\n";
	for (size_t i = 0; i < names.size(); i++) {
		std::ifstream f(std::string(argv[2]) + "/" + names[i], std::ios::binary | std::ios::ate);
		out << "    {\"" << names[i] << "\", reinterpret_cast<const char *>(a" << i << "), " << (size_t)f.tellg()
		    << ", \"" << mime_for(names[i]) << "\"},\n";
	}
	out << "};\n}  // namespace\n\nconst Asset *find_asset(std::string_view path) {\n"
	       "\tfor (const auto &a : table)\n\t\tif (path == a.path)\n\t\t\treturn &a;\n\treturn nullptr;\n}\n\n"
	       "}  // namespace wisp\n";
	return out ? 0 : 1;
}
